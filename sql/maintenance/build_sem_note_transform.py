"""Generate the SQL that turns the old SEM notes into results and comments.

The note used to be typed, which produced 163 spellings of five opinions. This
reads them, runs each one through :mod:`sem_note_rules`, and emits one script
an admin applies by hand, plus a CSV of every distinct note and what it was
read as, to be looked at before any of it is run.

It writes nothing to any database itself.

NOT A MIGRATION. It corrects data rather than shape, it is run once, and it is
deliberately outside the ledger. 020 adds the columns, this moves the data,
021 adds the key.

Run:
    venv\\Scripts\\python.exe sql\\maintenance\\build_sem_note_transform.py
    venv\\Scripts\\python.exe sql\\maintenance\\build_sem_note_transform.py --database dataloggingTest
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import sys
from collections import Counter
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from src.data_access.db_manager import DbManager  # noqa: E402
from src.data_access.sem_edx.sem_note_rules import (  # noqa: E402
    CATEGORIES,
    classify,
)

DEFAULT_DATABASE = "dataloggingDev"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "transform_sem_notes.sql"
DEFAULT_REVIEW = PROJECT_ROOT / "data" / "sem_notes" / "sem_note_mapping.csv"

HEADER = """/* transform_sem_notes.sql
   ---------------------------------------------------------------------------
   {samples} SEM samples carry a typed note. This reads each one as a result and
   a comment: {results} get one of the five, {comments} keep their text beside it, and
   {unread} say nothing a result can be read from and keep their text alone.

   GENERATED by sql/maintenance/build_sem_note_transform.py against {database}
   on {generated}, from {distinct} distinct notes. Every one of them is listed with
   what it was read as in data/sem_notes/sem_note_mapping.csv. Regenerate
   rather than editing.

   RUN AFTER 020 AND BEFORE 021. The columns have to exist, and the foreign key
   must not yet, or the first UPDATE here would be rejected by it.

   NOTHING IS REWRITTEN, ONLY MOVED. Where a note said more than its result,
   the comment is that note word for word: cutting the result out of somebody's
   sentence and keeping the rest produces text nobody wrote, and these are
   observations about a plate somebody looked at.

   EACH ROW NAMES WHAT IT EXPECTS TO FIND. A sample edited since this file was
   generated is left exactly as it is and reported at the end.

   Safe to re-run: the second pass finds nothing to match and changes nothing.
   --------------------------------------------------------------------------- */

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() NOT IN (N'dataloggingDev', N'dataloggingTest')
    THROW 50000, N'Refusing to run: not an expected database.', 1;

IF COL_LENGTH(N'[qc_data].[sem_sample]', N'comment') IS NULL
    THROW 50000, N'Run migration 020_sem_classification_type.sql first.', 1;

IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_sem_sample_note')
    THROW 50000, N'021 has already run. Drop FK_sem_sample_note, run this, add it back.', 1;

DECLARE @map TABLE (
    [generation] NVARCHAR(16) NOT NULL,
    [electrode]  NVARCHAR(32) NOT NULL,
    [position]   NVARCHAR(64) NOT NULL,
    /* What the sample must still say for this row to be applied. */
    [was]        NVARCHAR(512) NOT NULL,
    [result]    NVARCHAR(64)  NULL,
    [comment]    NVARCHAR(1024) NULL,
    PRIMARY KEY ([generation], [electrode], [position]));

INSERT INTO @map ([generation], [electrode], [position], [was], [result], [comment])
VALUES
"""

FOOTER = """
BEGIN TRANSACTION;

    UPDATE s
       SET s.[note]           = m.[result],
           s.[comment]        = m.[comment],
           s.[updated_at_utc] = SYSUTCDATETIME()
      FROM [qc_data].[sem_sample] AS s
      JOIN @map AS m
        ON m.[generation] = s.[generation]
       AND m.[electrode]  = s.[electrode]
       AND m.[position]   = s.[position]
     WHERE s.[note] = m.[was];

COMMIT TRANSACTION;

/* ---- what it did ----------------------------------------------------------- */
SELECT COUNT(*) AS [in_this_file],
       SUM(CASE WHEN s.[note] IS NULL AND m.[result] IS NULL THEN 1
                WHEN s.[note] = m.[result] THEN 1 ELSE 0 END) AS [done],
       SUM(CASE WHEN s.[electrode] IS NULL THEN 1 ELSE 0 END)  AS [sample_gone]
  FROM @map AS m
  LEFT JOIN [qc_data].[sem_sample] AS s
         ON s.[generation] = m.[generation]
        AND s.[electrode]  = m.[electrode]
        AND s.[position]   = m.[position];

/* Anything left holding its old text, named, so a skip is never silent. */
SELECT s.[electrode], s.[position], m.[was] AS [expected], s.[note] AS [found_now]
  FROM @map AS m
  JOIN [qc_data].[sem_sample] AS s
    ON s.[generation] = m.[generation]
   AND s.[electrode]  = m.[electrode]
   AND s.[position]   = m.[position]
 WHERE ISNULL(s.[note], N'') <> ISNULL(m.[result], N'')
 ORDER BY s.[electrode], s.[position];

/* And the five, as they stand afterwards. */
SELECT ISNULL(s.[note], N'(none)') AS [result], COUNT(*) AS [samples]
  FROM [qc_data].[sem_sample] AS s
 GROUP BY s.[note]
 ORDER BY COUNT(*) DESC;
"""


def text(value) -> str:
    """One NVARCHAR literal, or NULL where there is nothing to write."""
    clean = str(value or "").strip()
    return "N'" + clean.replace("'", "''") + "'" if clean else "NULL"


def connect(database: str) -> DbManager:
    """The app's own backend, pointed at ``database``, reads only."""
    original = DbManager._load_config
    DbManager._load_config = staticmethod(
        lambda path: {**original(path), "DB_PLANT_DATABASE": database})
    try:
        return DbManager(database=database)
    finally:
        DbManager._load_config = staticmethod(original)


def read_samples(manager: DbManager) -> list[dict]:
    """Every sample that carries a typed note."""
    rows = manager._session.rows(
        "SELECT [generation], [electrode], [position], [note] "
        "FROM [qc_data].[sem_sample] "
        "ORDER BY [generation], [electrode], [position]")
    return [row for row in rows if str(row.get("note") or "").strip()]


def planned(rows: list[dict]) -> list[dict]:
    """One entry per sample: what it says now, and what it will say."""
    plan = []
    for row in rows:
        note = str(row["note"]).strip()
        result, comment = classify(note)
        plan.append({"generation": str(row["generation"]).strip(),
                     "electrode": str(row["electrode"]).strip(),
                     "position": str(row["position"]).strip(),
                     "was": note, "result": result, "comment": comment})
    return plan


def build(plan: list[dict], counts: dict) -> str:
    """The whole script, values and all."""
    lines = [f"    ({text(row['generation'])}, {text(row['electrode'])}, "
             f"{text(row['position'])}, {text(row['was'])}, "
             f"{text(row['result'])}, {text(row['comment'])})"
             for row in plan]
    return HEADER.format(**counts) + ",\n".join(lines) + ";\n" + FOOTER


def write_review(plan: list[dict], path: Path) -> None:
    """Every distinct note and what it was read as, for a human to check."""
    seen: dict[str, dict] = {}
    for row in plan:
        entry = seen.setdefault(row["was"], {"result": row["result"],
                                             "comment": row["comment"],
                                             "samples": 0})
        entry["samples"] += 1
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["samples", "the note as typed", "read as",
                         "keeps a comment", "needs a human"])
        for note, entry in sorted(seen.items(),
                                  key=lambda item: (-item[1]["samples"], item[0])):
            writer.writerow([entry["samples"], note, entry["result"] or "",
                             "yes" if entry["comment"] else "",
                             "" if entry["result"] else "yes"])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", default=DEFAULT_DATABASE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--review", type=Path, default=DEFAULT_REVIEW)
    args = parser.parse_args()

    manager = connect(args.database)
    rows = read_samples(manager)
    if not rows:
        print(f"No typed notes in {args.database}. No file written.")
        return 0
    plan = planned(rows)

    results = Counter(row["result"] or "(none)" for row in plan)
    counts = {"samples": len(plan), "database": args.database,
              "generated": dt.date.today().isoformat(),
              "distinct": len({row["was"] for row in plan}),
              "results": sum(1 for row in plan if row["result"]),
              "comments": sum(1 for row in plan if row["comment"]),
              "unread": results.get("(none)", 0)}
    args.output.write_text(build(plan, counts), encoding="utf-8")
    write_review(plan, args.review)

    print(f"read {len(plan)} typed notes from {args.database}, "
          f"{counts['distinct']} distinct")
    for name in (*CATEGORIES, "(none)"):
        if results.get(name):
            print(f"  {results[name]:5d}  {name}")
    print(f"  {counts['comments']:5d}  also keep their text as a comment")
    print(f"wrote {args.output}")
    print(f"wrote {args.review}   <- read this one first")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
