    MERGE [qc_data].[electrode_failure_reason] WITH (HOLDLOCK) AS t
    USING @findings AS s ON t.[electrode] = s.[electrode]
    WHEN MATCHED THEN UPDATE SET
             /* What is already written down wins, so a rerun is a no-op. */
             t.[ic_result]  = COALESCE(t.[ic_result],  s.[ic_result]),
             t.[sem_result] = COALESCE(t.[sem_result], s.[sem_result])
    WHEN NOT MATCHED BY TARGET THEN
        INSERT ([electrode], [ic_result], [sem_result])
        VALUES (s.[electrode], s.[ic_result], s.[sem_result]);

