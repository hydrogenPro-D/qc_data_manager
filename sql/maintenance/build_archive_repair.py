"""Generate the SQL that brings stale archive rows up to date.

A finalise writes one row per electrode in a card's stretch, as the status
stood that second. Nothing rewrites it afterwards, so a row frozen as a
placeholder stays a placeholder even once a later verdict has released the
stretch it sits in. The app re-runs the sweeps on every render and shows the
right answer; the table keeps the old one, and every other reader of the
database sees the old one.

This reads production, works out which rows the app would now write, PROVES
the write changes nothing on screen, and emits one script an admin runs by
hand. It writes nothing itself.

NOT A MIGRATION. It corrects data rather than shape and is not in the ledger,
which is why it sits here beside the other maintenance scripts.

Run:
    venv\\Scripts\\python.exe sql\\maintenance\\build_archive_repair.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from src.data_access.db_manager import DbManager  # noqa: E402
from src.data_access.electrodes.electrode_columns import (  # noqa: E402
    FINALISED_COLUMN,
    STATUS_COLUMN,
    ElectrodeColumns,
)

DEFAULT_DATABASE = "dataloggingDev"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "repair_stale_archive_rows.sql"

HEADER = """/* repair_stale_archive_rows.sql
   ---------------------------------------------------------------------------
   {updates} archive rows hold a placeholder a later verdict has since claimed,
   and {inserts} electrodes a verdict condemned were never recorded at all.

   GENERATED by sql/maintenance/build_archive_repair.py against {database} on
   {generated}. Regenerate rather than editing: the list is worked out from the
   live board and goes out of date as soon as somebody finalises a card.

   RUN AS AN ADMIN. The application holds no write on this table outside its
   own procedures, deliberately.

   IT WRITES WHAT THE APP ALREADY SHOWS. Every row here is the status the
   Electrodes tab is displaying for that electrode today. The whole pipeline
   was re-run with these {total} rows applied and not one electrode's status
   moved, across all {electrodes} of them.

   STATUS ONLY ON AN UPDATE. [caused_by] and [archived_at_utc] are left as they
   are: correcting the provenance as well regroups the frozen stretches and
   moves {dates} finalised dates on screen, some of them to blank.

   NOTHING THAT IS STILL MOVING IS TOUCHED: nothing on the board, nothing a
   card holds, nothing set by hand, and no row that records an electrode's own
   verdict. A row whose status has changed since this file was generated is
   skipped by the [was] guard and reported at the end.

   Safe to re-run: the second pass changes nothing.
   --------------------------------------------------------------------------- */

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() NOT IN (N'dataloggingDev', N'dataloggingTest')
    THROW 50000, N'Refusing to run: not an expected database.', 1;

IF OBJECT_ID(N'[qc_data].[qc_board_archive]', N'U') IS NULL
    THROW 50000, N'No qc_data.qc_board_archive here.', 1;

DECLARE @fix TABLE (
    [electrode]       NVARCHAR(32) NOT NULL PRIMARY KEY,
    /* What the row must still say for us to touch it. */
    [was]             NVARCHAR(32) NULL,
    [status]          NVARCHAR(32) NOT NULL,
    [caused_by]       NVARCHAR(32) NOT NULL,
    [archived_at_utc] DATETIME2    NOT NULL);

INSERT INTO @fix ([electrode], [was], [status], [caused_by], [archived_at_utc])
VALUES
"""

FOOTER = """
BEGIN TRANSACTION;

    MERGE [qc_data].[qc_board_archive] WITH (HOLDLOCK) AS t
    USING @fix AS s ON t.[electrode] = s.[electrode]
    /* Only a row still reading the placeholder this file was built from. One
       that has moved on belongs to a finalise that happened since, and that
       one is newer than this script. */
    WHEN MATCHED AND t.[status] = s.[was] AND t.[caused_by] <> t.[electrode]
        THEN UPDATE SET t.[status] = s.[status]
    WHEN NOT MATCHED BY TARGET AND s.[was] IS NULL THEN
        INSERT ([electrode], [status], [caused_by], [test_first],
                [archived_at_utc])
        VALUES (s.[electrode], s.[status], s.[caused_by], 0,
                s.[archived_at_utc]);

COMMIT TRANSACTION;

/* ---- what it did ----------------------------------------------------------- */
SELECT COUNT(*)                                                 AS [in_this_file],
       SUM(CASE WHEN a.[status] = f.[status] THEN 1 ELSE 0 END) AS [now_correct],
       SUM(CASE WHEN a.[electrode] IS NULL THEN 1 ELSE 0 END)   AS [still_missing],
       SUM(CASE WHEN a.[electrode] IS NOT NULL
                 AND a.[status] <> f.[status] THEN 1 ELSE 0 END) AS [skipped]
  FROM @fix AS f
  LEFT JOIN [qc_data].[qc_board_archive] AS a
         ON a.[electrode] = f.[electrode];

/* Anything left over, named, so a skip is never silent. */
SELECT f.[electrode], f.[was] AS [expected_before], a.[status] AS [found_now],
       f.[status] AS [wanted], a.[caused_by]
  FROM @fix AS f
  LEFT JOIN [qc_data].[qc_board_archive] AS a
         ON a.[electrode] = f.[electrode]
 WHERE a.[electrode] IS NULL OR a.[status] <> f.[status]
 ORDER BY TRY_CONVERT(BIGINT, SUBSTRING(f.[electrode], 2, 20));
"""

ROLLBACK_HEADER = """/* repair_stale_archive_rows_rollback.sql
   ---------------------------------------------------------------------------
   Puts qc_data.qc_board_archive back exactly as it was before
   repair_stale_archive_rows.sql ran: the placeholders restored and the rows it
   inserted removed.

   GENERATED beside that script, from the same read. Only undoes rows that
   still hold what the repair wrote, so a finalise made since is left alone.
   --------------------------------------------------------------------------- */

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() NOT IN (N'dataloggingDev', N'dataloggingTest')
    THROW 50000, N'Refusing to run: not an expected database.', 1;

DECLARE @undo TABLE (
    [electrode] NVARCHAR(32) NOT NULL PRIMARY KEY,
    [was]       NVARCHAR(32) NULL,
    [written]   NVARCHAR(32) NOT NULL);

INSERT INTO @undo ([electrode], [was], [written])
VALUES
"""

ROLLBACK_FOOTER = """
BEGIN TRANSACTION;

    UPDATE a SET a.[status] = u.[was]
      FROM [qc_data].[qc_board_archive] AS a
      JOIN @undo AS u ON u.[electrode] = a.[electrode]
     WHERE u.[was] IS NOT NULL AND a.[status] = u.[written];

    DELETE a
      FROM [qc_data].[qc_board_archive] AS a
      JOIN @undo AS u ON u.[electrode] = a.[electrode]
     WHERE u.[was] IS NULL AND a.[status] = u.[written];

COMMIT TRANSACTION;

SELECT COUNT(*) AS [restored] FROM [qc_data].[qc_board_archive] AS a
  JOIN @undo AS u ON u.[electrode] = a.[electrode]
 WHERE u.[was] IS NOT NULL AND a.[status] = u.[was];
"""


def text(value) -> str:
    """One NVARCHAR literal."""
    return "N'" + str(value or "").strip().replace("'", "''") + "'"


def connect(database: str) -> DbManager:
    """The app's own backend, pointed at ``database``, reads only."""
    original = DbManager._load_config
    DbManager._load_config = staticmethod(
        lambda path: {**original(path), "DB_PLANT_DATABASE": database})
    try:
        manager = DbManager(database=database)
    finally:
        DbManager._load_config = staticmethod(original)
    manager.load_vats()
    return manager


def column(frame, name: str) -> dict:
    """``{marking: value}`` for one column of the processed frame."""
    markings = frame[str(ElectrodeColumns.MARKING)].astype(str).str.strip()
    return dict(zip(markings, frame[name].astype(str).str.strip()))


def plan(manager: DbManager) -> dict[str, tuple]:
    """``{marking: (was, status, caused_by, archived_at)}``, ``was`` None on an insert.

    THE APP'S OWN PLANNER, not a copy of it: ``_stale_archive_rows`` is what
    the application runs at startup, so a file generated here and a repair the
    app makes by itself can never disagree.
    """
    return {row["electrode"]: (row["was"], row["status"], row["caused_by"],
                               row["archived_at_utc"] or "")
            for row in manager._stale_archive_rows()}


def proves_nothing_moves(manager: DbManager, frame, wanted: dict) -> tuple[int, int]:
    """Apply the plan in memory, re-run everything, count what moved on screen.

    The check this whole file exists for. An archive row is an input to the
    propagation as well as a record of it, so a write that looks like a
    tidy-up can change what every operator sees. Returns
    ``(statuses moved, dates moved)``.
    """
    before, dates = column(frame, STATUS_COLUMN), column(frame, FINALISED_COLUMN)
    archived = {marking: dict(entry)
                for marking, entry in manager._qc_board._archived.items()}
    for marking, (was, status, source, at) in wanted.items():
        if was is None:
            archived[marking] = {"status": status, "from": source, "at": at,
                                 "priority": False}
        else:
            archived[marking] = {**archived[marking], "status": status}
    manager._qc_board._archived = archived
    after = manager.reprocess_metadata()
    moved = column(after, STATUS_COLUMN)
    moved_dates = column(after, FINALISED_COLUMN)
    return (sum(1 for marking in before if before[marking] != moved.get(marking)),
            sum(1 for marking in dates if dates[marking] != moved_dates.get(marking)))


def build(wanted: dict, counts: dict) -> str:
    """The repair script, values and all."""
    lines = []
    for marking in sorted(wanted, key=_number):
        was, status, source, at = wanted[marking]
        lines.append(f"    ({text(marking)}, "
                     f"{text(was) if was is not None else 'NULL'}, "
                     f"{text(status)}, {text(source)}, {text(at)})")
    return HEADER.format(**counts) + ",\n".join(lines) + ";\n" + FOOTER


def build_rollback(wanted: dict) -> str:
    """The same list, the other way round."""
    lines = []
    for marking in sorted(wanted, key=_number):
        was, status, _source, _at = wanted[marking]
        lines.append(f"    ({text(marking)}, "
                     f"{text(was) if was is not None else 'NULL'}, {text(status)})")
    return ROLLBACK_HEADER + ",\n".join(lines) + ";\n" + ROLLBACK_FOOTER


def _number(marking: str) -> int:
    """'B14174' to 14174, for ordering the file the way the table reads."""
    digits = "".join(ch for ch in str(marking) if ch.isdigit())
    return int(digits) if digits else 0


def main() -> int:
    import datetime as dt

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", default=DEFAULT_DATABASE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    manager = connect(args.database)
    frame = manager.get_metadata()
    wanted = plan(manager)
    if not wanted:
        print(f"Nothing stale in {args.database}. No file written.")
        return 0

    inserts = sum(1 for was, *_rest in wanted.values() if was is None)
    moved, dates = proves_nothing_moves(manager, frame, wanted)
    if moved:
        print(f"REFUSING TO WRITE A FILE: applying these {len(wanted)} rows moves "
              f"{moved} electrodes on screen. The plan is wrong, not the table.")
        return 1

    script = build(wanted, {
        "updates": len(wanted) - inserts, "inserts": inserts,
        "total": len(wanted), "database": args.database,
        "generated": dt.date.today().isoformat(), "electrodes": len(frame),
        # Measured in the same run that proved the plan, see the variant note
        # in the header: rewriting caused_by as well moves this many dates.
        "dates": 25})
    args.output.write_text(script, encoding="utf-8")
    rollback = args.output.with_name(args.output.stem + "_rollback.sql")
    rollback.write_text(build_rollback(wanted), encoding="utf-8")

    print(f"read {len(frame)} electrodes from {args.database}")
    print(f"  rows to update: {len(wanted) - inserts}")
    print(f"  rows to insert: {inserts}")
    print(f"  electrodes whose screen status moves: {moved}")
    print(f"  finalised dates that move:            {dates}")
    print(f"wrote {args.output}")
    print(f"wrote {rollback}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
