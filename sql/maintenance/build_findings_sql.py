"""Turn the upload CSV into one SQL script an admin runs by hand.

Second half of the backfill. ``build_findings_upload.py`` makes the CSV, this
makes the statement, and neither of them writes to a database: the script it
produces is run by somebody logged in as an admin.

NOT A MIGRATION, deliberately. It corrects data rather than shape, it is run
once, and it is not in the ledger, which is why it lives here beside the other
maintenance scripts rather than under sql/migrations.

Run:
    venv\\Scripts\\python.exe sql\\maintenance\\build_findings_sql.py
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from src.data_access.qc_board.qc_board_columns import (  # noqa: E402
    IC_RESULT,
    SEM_RESULT,
)

DEFAULT_SOURCE = PROJECT_ROOT / "data" / "findings_backfill" / "findings_upload.csv"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "backfill_failure_reasons.sql"

# qc_data.electrode_status.updated_at_utc for every source = 'tested' row: the
# one bulk ETL import, and the only date this database holds for these verdicts.
ETL_IMPORTED_AT = "2026-08-26T07:50:42.148033"

HEADER = """/* backfill_failure_reasons.sql
   ---------------------------------------------------------------------------
   Why {count} electrodes scrapped after testing failed, from QC's own records.

   GENERATED by sql/maintenance/build_findings_sql.py from
   data/findings_backfill/findings_upload.csv. Edit the CSV and regenerate;
   do not edit this file.

   RUN AS AN ADMIN. The application holds SELECT on this table and nothing
   more, deliberately: these rows correct history and are not something an
   operator edits.

   IT WRITES TO electrode_failure_reason, NOT TO qc_board_archive. An archive
   row is read twice, once as a record and once as a decision the propagation
   sweeps from, so filling it turned {inserts} old failures into live verdicts and
   produced 808 electrodes reading Waiting for additional SEM approval. Nothing
   reads this table as a decision, so nothing here can sweep.

   LOWEST PRECEDENCE. The live card wins, then the archive, then this. An
   electrode the board has judged is never described by these rows, so the {updates}
   that already carry a finding on their archive row are unaffected by what is
   written here.

   NOTHING ALREADY RECORDED IS OVERWRITTEN, and nothing is deleted. Safe to
   re-run: the second pass changes nothing.
   --------------------------------------------------------------------------- */

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() NOT IN (N'dataloggingDev', N'dataloggingTest')
    THROW 50000, N'Refusing to run: not an expected database.', 1;

IF OBJECT_ID(N'[qc_data].[electrode_failure_reason]', N'U') IS NULL
    THROW 50000, N'Run migration 018_electrode_failure_reason.sql first.', 1;

DECLARE @findings TABLE (
    [electrode]  NVARCHAR(32) NOT NULL PRIMARY KEY,
    [{ic}]  NVARCHAR(16) NULL,
    [{sem}] NVARCHAR(16) NULL);

INSERT INTO @findings ([electrode], [{ic}], [{sem}])
VALUES
"""

FOOTER = """
BEGIN TRANSACTION;

    MERGE [qc_data].[electrode_failure_reason] WITH (HOLDLOCK) AS t
    USING @findings AS s ON t.[electrode] = s.[electrode]
    WHEN MATCHED THEN UPDATE SET
             /* What is already written down wins, so a rerun is a no-op. */
             t.[{ic}]  = COALESCE(t.[{ic}],  s.[{ic}]),
             t.[{sem}] = COALESCE(t.[{sem}], s.[{sem}])
    WHEN NOT MATCHED BY TARGET THEN
        INSERT ([electrode], [{ic}], [{sem}])
        VALUES (s.[electrode], s.[{ic}], s.[{sem}]);

COMMIT TRANSACTION;

/* ---- what it did ----------------------------------------------------------- */
SELECT COUNT(*)                                            AS [in_this_file],
       SUM(CASE WHEN r.[electrode] IS NULL THEN 1 ELSE 0 END) AS [still_missing],
       SUM(CASE WHEN r.[{sem}] IS NOT NULL THEN 1 ELSE 0 END) AS [with_sem],
       SUM(CASE WHEN r.[{ic}]  IS NOT NULL THEN 1 ELSE 0 END) AS [with_ic]
  FROM @findings AS f
  LEFT JOIN [qc_data].[electrode_failure_reason] AS r
         ON r.[electrode] = f.[electrode];
"""


def sql_text(value: str) -> str:
    """One NVARCHAR literal, or NULL where the finding is blank."""
    clean = str(value or "").strip()
    if not clean:
        return "NULL"
    return "N'" + clean.replace("'", "''") + "'"


def build(rows: list[dict], updates: int, inserts: int) -> str:
    """The whole script, values and all."""
    fields = {"ic": IC_RESULT, "sem": SEM_RESULT}
    lines = []
    for row in rows:
        lines.append(
            f"    ({sql_text(row['electrode'])}, "
            f"{sql_text(row[IC_RESULT])}, {sql_text(row[SEM_RESULT])})")
    body = ",\n".join(lines) + ";\n"
    head = HEADER.format(count=len(rows), updates=updates, inserts=inserts,
                         **fields)
    return head + body + FOOTER.format(**fields)


def count_existing(markings: list[str]) -> tuple[int, int]:
    """How many are already in the archive, read only, on production."""
    import json

    import pyodbc

    cfg = json.loads((PROJECT_ROOT / "config" / "db_connection.json")
                     .read_text(encoding="utf-8"))
    connection = (f"DRIVER={{{cfg['DB_DRIVER']}}};SERVER={cfg['DB_SERVER']};"
                  f"DATABASE=dataloggingDev;UID={cfg['DB_USERNAME']};"
                  f"PWD={cfg['DB_PASSWORD']};Encrypt=yes;"
                  "TrustServerCertificate=no;Connection Timeout=30")
    cursor = pyodbc.connect(connection).cursor()
    cursor.execute("SELECT electrode FROM qc_data.vw_qc_board_archive")
    archived = {str(r[0]).strip() for r in cursor.fetchall()}
    updates = sum(1 for m in markings if m in archived)
    return updates, len(markings) - updates


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--offline", action="store_true",
                        help="skip the read of production used for the header")
    args = parser.parse_args()

    with args.source.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        print(f"Nothing in {args.source}.")
        return 1

    markings = [r["electrode"] for r in rows]
    updates, inserts = (0, len(rows)) if args.offline else count_existing(markings)

    args.output.write_text(build(rows, updates, inserts), encoding="utf-8")
    print(f"read  {len(rows)} rows from {args.source}")
    print(f"wrote {args.output}")
    print(f"  already in the archive, an update: {updates}")
    print(f"  not there yet, a new row:          {inserts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
