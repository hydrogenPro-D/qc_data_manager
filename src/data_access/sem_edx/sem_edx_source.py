"""Reads and writes the SEM EDX measurements and the sheet layout beside them.

``data/csv/sem_edx_gen4_1.csv`` is generated by
``data/ETL/03_import_sem_edx_gen4_1.py`` from the Gen 4.1 workbook, and
``04_load_to_database.py`` loads it into the qc_data schema. The application
itself no longer reads these files: they are the input to the pipeline, not a
backend.

The element columns are not fixed. Whatever ``<symbol>_pct`` columns are present
get read, so a new element on the sheet needs no change here. Which of them a
tab *shows* is configuration, in ``sem_edx.layout`` in config/config.json.

A missing file yields an empty frame rather than an error.

Named per generation on purpose: each workbook loads through the same reader.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from src.data_access import app_config
from src.data_access.sem_edx import sem_edx_library
from src.data_access.sem_edx.sem_edx_columns import (
    SemEdxColumns,
    FIXED_COLUMNS,
    element_symbol,
)

# The generations, oldest first, which is the order their tabs appear in. The
# label is what an operator sees; the slug is what the files are named after.
GENERATIONS: dict[str, str] = {
    "Gen3.1": "gen3_1",
    "Gen4.1": "gen4_1",
}
DEFAULT_GENERATION = "Gen4.1"


def generation_slug(generation: str) -> str:
    """``'Gen3.1'`` -> ``'gen3_1'``, the part of a filename that names it."""
    return GENERATIONS.get(str(generation).strip(),
                           str(generation).strip().lower().replace(".", "_"))


def sem_edx_csv_path(generation: str = DEFAULT_GENERATION) -> Path:
    """Where a generation's measurement file lives."""
    return (app_config.base_directory() / "data" / "csv"
            / f"sem_edx_{generation_slug(generation)}.csv")


def portable_folder(folder, ask=None) -> str:
    """A result folder as it should be stored, or "" if it cannot be.

    The absolute path is personal: it starts with the operator's own user
    folder, so a row written by one person names a location nobody else has.
    Everything below the synced library root is identical for everyone, so that
    tail is what gets stored and each machine resolves it against its own root.

    Returns "" rather than the absolute path when the library cannot be found,
    even after asking. Storing the personal path is worse than storing nothing:
    it looks like it worked, and then opens for exactly one person. The caller
    refuses the import on an empty answer.
    """
    text = str(folder or "").strip()
    if not text:
        return ""

    path = Path(text)
    if not path.is_absolute():
        return text          # already a tail

    try:
        path = path.resolve()
    except OSError:
        return ""

    root = sem_edx_library.image_root(ask)
    if root is None:
        return ""
    try:
        return str(path.relative_to(root.resolve()))
    except (ValueError, OSError):
        return ""


def resolve_folder(stored, ask=None) -> Path | None:
    """Where a stored folder actually is on this machine, or None.

    A tail is joined to whichever root this machine has. An absolute path is
    honoured as-is, which is what keeps a row written before the library was
    findable working for whoever wrote it.
    """
    text = str(stored or "").strip()
    if not text:
        return None

    path = Path(text)
    if path.is_absolute():
        return path if path.is_dir() else None

    root = sem_edx_library.image_root(ask)
    if root is None:
        return None
    candidate = root / path
    return candidate if candidate.is_dir() else None


def measured_columns(df: pd.DataFrame) -> list[str]:
    """The element columns a frame actually carries, in its own order."""
    return [str(c) for c in df.columns if element_symbol(str(c))]


def load_sem_edx(generation: str = DEFAULT_GENERATION,
                 path: Path | None = None) -> pd.DataFrame:
    """One generation's raw measurements, one row each.

    Empty frame when the file is absent. The measured percentages are coerced
    to numbers here, once, so nothing downstream has to parse text.
    """
    path = path or sem_edx_csv_path(generation)
    if not path.exists():
        print(f"No SEM EDX file at {path}. Run "
              f"data/ETL/03_import_sem_edx_gen4_1.py to generate it.")
        return pd.DataFrame(columns=list(FIXED_COLUMNS))

    try:
        df = pd.read_csv(path, encoding="utf-8-sig", dtype=str, keep_default_na=False)
    except (OSError, pd.errors.ParserError) as e:
        print(f"Could not read {path}: {e}")
        return pd.DataFrame(columns=list(FIXED_COLUMNS))

    for column in FIXED_COLUMNS:
        if column not in df.columns:
            df[column] = ""
    elements = measured_columns(df)
    for column in elements:
        df[column] = pd.to_numeric(df[column], errors="coerce")
    measurement = str(SemEdxColumns.MEASUREMENT)
    df[measurement] = pd.to_numeric(df[measurement], errors="coerce").fillna(0).astype(int)

    return df[[*FIXED_COLUMNS, *elements]]


def save_sem_edx(df: pd.DataFrame, generation: str = DEFAULT_GENERATION,
                 path: Path | None = None) -> None:
    """Write one generation's measurements back out, one row each.

    The same shape ``load_sem_edx`` reads, so a file the app wrote and one the
    ETL script wrote are indistinguishable. Element columns are sorted, since
    their order carries no meaning: the layout file decides how they are shown.
    """
    path = path or sem_edx_csv_path(generation)
    path.parent.mkdir(parents=True, exist_ok=True)

    elements = sorted(measured_columns(df))
    out = df.reindex(columns=[*FIXED_COLUMNS, *elements])
    # Shortened on every write, so a row saved with a personal path before the
    # roots were configured becomes portable the next time anything is saved.
    folder = str(SemEdxColumns.FOLDER)
    out[folder] = out[folder].map(portable_folder)
    for column in elements:
        # %g so 38.0 goes back out as 38, matching what the ETL script writes.
        out[column] = out[column].map(
            lambda v: "" if pd.isna(v) else f"{float(v):g}")
    out.to_csv(path, index=False, encoding="utf-8", lineterminator="\n")
